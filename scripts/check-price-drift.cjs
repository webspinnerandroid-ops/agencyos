function classifyDrift(stored, liveCents) {
  if (liveCents == null) {
    return stored == null ? "NO STORED PRICE" : "NO STRIPE PRICE";
  }
  if (stored == null) return "DRIFT (stored unparseable)";
  return Math.abs(stored - liveCents / 100) > 1e-3 ? "DRIFT" : "SYNCED";
}
