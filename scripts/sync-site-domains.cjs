#!/usr/bin/env node
/**
 * sync-site-domains.cjs — apply custom-domain vhosts for CMS sites.
 *
 * Reads the `site_domains` table (domain → site_slug) and generates an nginx
 * server block per domain that proxies to the Next.js app on 127.0.0.1:3000
 * while preserving the Host header, so the app's middleware can rewrite
 * client.com → /site/<slug>.
 *
 * Usage:  node scripts/sync-site-domains.cjs [--print-only]
 *
 * The VPS is a Plesk box; custom config lives in /etc/nginx/conf.d/ (Plesk
 * won't touch that directory). The script tries to apply over SSH with
 * passwordless sudo; if that isn't available it prints the config and the
 * manual steps. Point each domain's DNS A record at the VPS IP first.
 */
const fs = require("fs");
const path = require("path");
const { execSync } = require("child_process");
const { createClient } = require("@supabase/supabase-js");

const HOST = "154.12.243.255";
const USER = "platform";
const PASS = "~Op3d9y&DFtz2ass";
const PLINK = "C:\\Program Files\\PuTTY\\plink.exe";
const PSCP = "C:\\Program Files\\PuTTY\\pscp.exe";
const CONF_NAME = "agencyos-sites.conf";
const REMOTE_CONF = `/etc/nginx/conf.d/${CONF_NAME}`;
const PRINT_ONLY = process.argv.includes("--print-only");

// Load env the same way the app does.
for (const line of fs.readFileSync(path.join(__dirname, "..", ".env.local"), "utf8").split("\n")) {
  const m = line.match(/^([A-Z0-9_]+)=(.*)$/);
  if (m && !process.env[m[1]]) process.env[m[1]] = m[2];
}

async function loadDomains() {
  const sb = createClient(process.env.NEXT_PUBLIC_SUPABASE_URL, process.env.SUPABASE_SERVICE_ROLE_KEY);
  const { data, error } = await sb.from("site_domains").select("domain, site_slug");
  if (error) throw new Error("Fetch site_domains: " + error.message);
  return (data ?? []).filter((d) => d.domain && d.site_slug);
}

function generateConf(domains) {
  const blocks = domains
    .map((d) => {
      const esc = d.domain.replace(/\./g, "\\.");
      return `# ${d.domain} -> /site/${d.site_slug}
server {
    listen 80;
    server_name ${d.domain} www.${d.domain};

    # Uncomment once HTTPS is set up (certbot):
    # listen 443 ssl;
    # ssl_certificate     /etc/letsencrypt/live/${d.domain}/fullchain.pem;
    # ssl_certificate_key /etc/letsencrypt/live/${d.domain}/privkey.pem;

    location / {
        proxy_pass http://127.0.0.1:3000;
        proxy_http_version 1.1;
        proxy_set_header Host $host;
        proxy_set_header X-Forwarded-For $proxy_add_x_forwarded_for;
        proxy_set_header X-Forwarded-Proto $scheme;
    }
}`;
    })
    .join("\n\n");
  return `# Generated by scripts/sync-site-domains.cjs — do not edit by hand.\n${blocks}\n`;
}

function ssh(cmd) {
  const full = `"${PLINK}" -pw "${PASS}" -batch ${USER}@${HOST} "${cmd.replace(/"/g, '\\"')}"`;
  return execSync(full, { encoding: "utf-8", stdio: ["ignore", "pipe", "pipe"], shell: "cmd.exe" });
}

(async () => {
  try {
    const domains = await loadDomains();
    const conf = generateConf(domains);

    if (domains.length === 0) {
      console.log("No custom domains mapped yet — nothing to do.");
      return;
    }

    console.log(`Generated ${domains.length} vhost(s):`);
    for (const d of domains) console.log(`  ${d.domain} -> /site/${d.site_slug}`);

    if (PRINT_ONLY) {
      console.log("\n----- " + CONF_NAME + " -----\n" + conf);
      return;
    }

    // Write the conf to /tmp, then move it into place with passwordless sudo.
    const local = path.join(require("os").tmpdir(), CONF_NAME);
    fs.writeFileSync(local, conf);
    const scp = `"${PSCP}" -pw "${PASS}" -batch "${local}" ${USER}@${HOST}:/tmp/${CONF_NAME}`;
    execSync(scp, { encoding: "utf-8", shell: "cmd.exe" });

    try {
      ssh(`sudo -n cp /tmp/${CONF_NAME} ${REMOTE_CONF} && sudo -n nginx -t && sudo -n systemctl reload nginx && echo APPLIED`);
      console.log("\nApplied to the VPS and nginx reloaded. Point DNS A records at " + HOST + ".");
    } catch {
      console.log(
        "\nCould not apply automatically (needs passwordless sudo on the VPS). Manual steps:\n" +
        `  ssh ${USER}@${HOST}\n` +
        `  sudo cp /tmp/${CONF_NAME} ${REMOTE_CONF}\n` +
        "  sudo nginx -t && sudo systemctl reload nginx\n" +
        "\nConfig preview:\n" + conf
      );
    }
  } catch (err) {
    console.error("sync-site-domains failed:", err.message);
    process.exit(1);
  }
})();
