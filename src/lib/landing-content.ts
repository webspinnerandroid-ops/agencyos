// ---------------------------------------------------------------------------
// Sanitization — never trust DB content when rendering the public page.
// ---------------------------------------------------------------------------

function asString(value: unknown, fallback: string): string {
  return typeof value === "string" && value.trim().length > 0
    ? value.trim()
    : fallback;
}

function asStringArray(value: unknown): string[] | null {
  if (!Array.isArray(value)) return null;
  const out: string[] = [];
  for (const v of value) {
    if (typeof v === "string" && v.trim()) out.push(v.trim());
  }
  return out.length ? out : null;
}

function asFeatures(value: unknown): LandingFeature[] | null {
  if (!Array.isArray(value)) return null;
  const out: LandingFeature[] = [];
  for (const v of value) {
    if (!v || typeof v !== "object") continue;
    const item = v as Record<string, unknown>;
    const title = typeof item.title === "string" ? item.title.trim() : "";
    const description =
      typeof item.description === "string" ? item.description.trim() : "";
    if (title) out.push({ title, description });
  }
  return out.length ? out : null;
}

function asSteps(value: unknown): LandingStep[] | null {
  if (!Array.isArray(value)) return null;
  const out: LandingStep[] = [];
  for (const v of value) {
    if (!v || typeof v !== "object") continue;
    const item = v as Record<string, unknown>;
    const title = typeof item.title === "string" ? item.title.trim() : "";
    if (!title) continue;
    out.push({
      step: typeof item.step === "string" ? item.step.trim() : "",
      title,
      description:
        typeof item.description === "string" ? item.description.trim() : "",
    });
  }
  return out.length ? out : null;
}

function asLogos(value: unknown): LandingLogo[] | null {
  if (!Array.isArray(value)) return null;
  const out: LandingLogo[] = [];
  for (const v of value) {
    if (!v || typeof v !== "object") continue;
    const item = v as Record<string, unknown>;
    const name = typeof item.name === "string" ? item.name.trim() : "";
    const url = typeof item.url === "string" ? item.url.trim() : "";
    if (!url) continue;
    out.push({
      name: name || url,
      url,
      href: typeof item.href === "string" ? item.href.trim() : undefined,
    });
  }
  return out.length ? out : null;
}

function asTestimonials(value: unknown): LandingTestimonial[] | null {
  if (!Array.isArray(value)) return null;
  const out: LandingTestimonial[] = [];
  for (const v of value) {
    if (!v || typeof v !== "object") continue;
    const item = v as Record<string, unknown>;
    const quote = typeof item.quote === "string" ? item.quote.trim() : "";
    if (!quote) continue;
    out.push({
      quote,
      author: typeof item.author === "string" ? item.author.trim() : "",
    });
  }
  return out.length ? out : null;
}

function asPlans(value: unknown): LandingPlan[] | null {
  if (!Array.isArray(value)) return null;
  const out: LandingPlan[] = [];
  for (const v of value) {
    if (!v || typeof v !== "object") continue;
    const item = v as Record<string, unknown>;
    const planId = typeof item.planId === "string" ? item.planId.trim() : "";
    const name = typeof item.name === "string" ? item.name.trim() : "";
    if (!planId || !name) continue;
    out.push({
      planId,
      name,
      price: typeof item.price === "string" ? item.price.trim() : "",
      description:
        typeof item.description === "string" ? item.description.trim() : "",
      features: asStringArray(item.features) ?? [],
      popular: item.popular === true,
    });
  }
  return out.length ? out : null;
}

function asHubs(value: unknown): LandingHub[] | null {
  if (!Array.isArray(value)) return null;
  const out: LandingHub[] = [];
  for (const v of value) {
    if (!v || typeof v !== "object") continue;
    const item = v as Record<string, unknown>;
    const hubId = typeof item.hubId === "string" ? item.hubId.trim() : "";
    const name = typeof item.name === "string" ? item.name.trim() : "";
    if (!hubId || !name) continue;
    out.push({
      hubId,
      name,
      price: typeof item.price === "string" ? item.price.trim() : "",
      blurb: typeof item.blurb === "string" ? item.blurb.trim() : "",
    });
  }
  return out.length ? out : null;
}

function asFaqs(value: unknown): LandingFaq[] | null {
  if (!Array.isArray(value)) return null;
  const out: LandingFaq[] = [];
  for (const v of value) {
    if (!v || typeof v !== "object") continue;
    const item = v as Record<string, unknown>;
    const q = typeof item.q === "string" ? item.q.trim() : "";
    if (!q) continue;
    out.push({ q, a: typeof item.a === "string" ? item.a.trim() : "" });
  }
  return out.length ? out : null;
}

function asPages(value: unknown): LandingPage[] | null {
  if (!Array.isArray(value)) return null;
  const out: LandingPage[] = [];
  const seen = new Set<string>();
  for (const v of value) {
    if (!v || typeof v !== "object") continue;
    const item = v as Record<string, unknown>;
    const title = typeof item.title === "string" ? item.title.trim() : "";
    const slug =
      typeof item.slug === "string" ? item.slug.trim().toLowerCase() : "";
    const body = typeof item.body === "string" ? item.body : "";
    if (!title || !slug) continue;
    // Only safe URL-safe slugs (lowercase + dashes) — never external paths.
    if (!/^[a-z0-9]+(?:-[a-z0-9]+)*$/.test(slug)) continue;
    if (seen.has(slug)) continue;
    seen.add(slug);
    out.push({ slug, title, body });
  }
  return out.length ? out : null;
}

function asNavLinks(value: unknown): LandingNavLink[] | null {
  if (!Array.isArray(value)) return null;
  const out: LandingNavLink[] = [];
  for (const v of value) {
    if (!v || typeof v !== "object") continue;
    const item = v as Record<string, unknown>;
    const label = typeof item.label === "string" ? item.label.trim() : "";
    const href = typeof item.href === "string" ? item.href.trim() : "";
    // Same-app paths only — no javascript: or external URLs.
    if (!label || !href.startsWith("/") || href.includes("://")) continue;
    out.push({ label: label.slice(0, 40), href: href.slice(0, 200) });
  }
  return out.length ? out : null;
}

/**
 * Merge stored content over the compiled defaults field-by-field. Empty/absent
 * values fall back so the public page is never left blank.
 */
export function mergeLandingContent(raw: unknown): LandingContent {
  const d = DEFAULT_LANDING_CONTENT;
  const r = (raw && typeof raw === "object" ? raw : {}) as Record<string, unknown>;

  return {
    heroTitle: asString(r.heroTitle, d.heroTitle),
    heroSubtitle: asString(r.heroSubtitle, d.heroSubtitle),
    heroBadge: asString(r.heroBadge, d.heroBadge),
    featuresHeading: asString(r.featuresHeading, d.featuresHeading),
    featuresSubheading: asString(r.featuresSubheading, d.featuresSubheading),
    features: asFeatures(r.features) ?? d.features,
    howItWorksHeading: asString(r.howItWorksHeading, d.howItWorksHeading),
    howItWorksSubheading: asString(r.howItWorksSubheading, d.howItWorksSubheading),
    howItWorks: asSteps(r.howItWorks) ?? d.howItWorks,
    logoStripHeading: asString(r.logoStripHeading, d.logoStripHeading),
    logos: asLogos(r.logos) ?? d.logos,
    testimonialsHeading: asString(r.testimonialsHeading, d.testimonialsHeading),
    testimonials: asTestimonials(r.testimonials) ?? d.testimonials,
    faqHeading: asString(r.faqHeading, d.faqHeading),
    faqs: asFaqs(r.faqs) ?? d.faqs,
    pricingHeading: asString(r.pricingHeading, d.pricingHeading),
    pricingSubheading: asString(r.pricingSubheading, d.pricingSubheading),
    plans: asPlans(r.plans) ?? d.plans,
    hubsHeading: asString(r.hubsHeading, d.hubsHeading),
    hubsSubheading: asString(r.hubsSubheading, d.hubsSubheading),
    hubs: asHubs(r.hubs) ?? d.hubs,
    ctaTitle: asString(r.ctaTitle, d.ctaTitle),
    ctaSubtitle: asString(r.ctaSubtitle, d.ctaSubtitle),
    ctaButton: asString(r.ctaButton, d.ctaButton),
    pages: asPages(r.pages) ?? d.pages,
    navLinks: asNavLinks(r.navLinks) ?? d.navLinks,
  };
}

