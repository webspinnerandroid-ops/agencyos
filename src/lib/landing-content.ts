// ============================================================================
// Landing page content model
//
// The public marketing page (/ ) reads from site_settings.landing_content,
// falling back to the compiled defaults below whenever a field is missing or
// the column is null. The super admin edits all of this in the visual page
// builder at /dashboard/admin/page-builder.
// ============================================================================

export interface LandingLogo {
  name: string;
  url: string;
  href?: string;
}

export interface LandingFeature {
  title: string;
  description: string;
}

export interface LandingStep {
  step: string;
  title: string;
  description: string;
}

export interface LandingTestimonial {
  quote: string;
  author: string;
}

export interface LandingFaq {
  q: string;
  a: string;
}

/** A pricing tier. `planId` is the Stripe sync key (product metadata
 * `plan_id`) — it must stay in sync with Stripe, so the builder renders it
 * read-only. Everything else is editable display copy. */
export interface LandingPlan {
  planId: string;
  name: string;
  price: string;
  description: string;
  features: string[];
  popular?: boolean;
}

/** An a-la-carte hub add-on. `hubId` is the Stripe sync key (product metadata
 * `hub_id`) — read-only in the builder. */
export interface LandingHub {
  hubId: string;
  name: string;
  price: string;
  blurb: string;
}

/** A standalone marketing page (rendered at /p/<slug>). */
export interface LandingPage {
  slug: string;
  title: string;
  body: string;
}

/** A custom link shown in the landing page header navigation. */
export interface LandingNavLink {
  label: string;
  href: string;
}

export interface LandingContent {
  heroTitle: string;
  heroSubtitle: string;
  heroBadge: string;
  featuresHeading: string;
  featuresSubheading: string;
  features: LandingFeature[];
  howItWorksHeading: string;
  howItWorksSubheading: string;
  howItWorks: LandingStep[];
  logoStripHeading: string;
  logos: LandingLogo[];
  testimonialsHeading: string;
  testimonials: LandingTestimonial[];
  faqHeading: string;
  faqs: LandingFaq[];
  pricingHeading: string;
  pricingSubheading: string;
  plans: LandingPlan[];
  hubsHeading: string;
  hubsSubheading: string;
  hubs: LandingHub[];
  ctaTitle: string;
  ctaSubtitle: string;
  ctaButton: string;
  pages: LandingPage[];
  navLinks: LandingNavLink[];
}

